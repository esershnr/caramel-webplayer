/**
 * Generates src/template.ts from the skin source.
 *
 * - `<media-icon name="x" class="...">` becomes an inline Lucide <svg> (SSR friendly,
 *   no icon registry needed at runtime). Existing class names are preserved so
 *   the skin stylesheet keeps targeting them.
 * - Random element ids (`vjs-XXXXXXXX-0...`) become `{{uid}}-N` placeholders so
 *   several players can share a page.
 * - The media placeholder comment becomes `<!--esp:media-->`.
 *
 * Run with: pnpm --filter @esershnr/caramel-skin build:template
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIcon, iconToSvg } from '@esershnr/caramel-icons';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'src/components/videojs/video/skin.html');
const target = resolve(root, 'src/template.ts');

/** Video.js icon names that still appear in skin.html mapped to our registry. */
const ICON_ALIASES: Record<string, string> = {
  'airplay-enter': 'airplay',
  'airplay-exit': 'airplay',
  'cast-enter': 'cast',
  'cast-exit': 'cast',
  gear: 'settings',
  switches: 'quality',
};

let html = readFileSync(source, 'utf8');

// 0. The license notice at the top of skin.html moves to the generated file
//    header; the template itself must start with <media-container>.
const notice = /^\s*<!--([\s\S]*?)-->\s*/.exec(html);
html = html.slice(notice?.[0].length ?? 0);

// 1. Media placeholder
html = html.replace('<!-- Add a compatible media component here. -->', '<!--esp:media-->');

// 2. Inline static icons
const missing = new Set<string>();
html = html.replace(
  /<media-icon\s+name="([a-z-]+)"([^>]*)>\s*<\/media-icon>/g,
  (match, name: string, rest: string) => {
    const iconName = ICON_ALIASES[name] ?? name;
    const node = getIcon(iconName);
    if (!node) {
      missing.add(name);
      return match;
    }
    const classMatch = /class="([^"]*)"/.exec(rest);
    const className = classMatch?.[1];
    const extra = `esp-icon esp-icon-${iconName}`;
    return iconToSvg(node, { className: className ? `${className} ${extra}` : extra });
  },
);
if (missing.size) {
  throw new Error(`No Lucide mapping for Video.js icons: ${[...missing].join(', ')}`);
}

// 3. Stable id placeholders
const tokens = new Map<string, number>();
html = html.replace(/vjs-([A-Za-z0-9_-]{8})-0/g, (_m, token: string) => {
  if (!tokens.has(token)) tokens.set(token, tokens.size);
  return `{{uid}}-${tokens.get(token)}`;
});

// 4. Collapse whitespace between tags to keep the bundle small
html = html
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)
  .join('');

const noticeLines = (notice?.[1] ?? '')
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => `// ${line}`)
  .join('\n');
const out = `// Generated by scripts/build-template.ts from components/videojs/video/skin.html. Do not edit.
${noticeLines}
export const SKIN_TEMPLATE = ${JSON.stringify(html)};
`;
writeFileSync(target, out);
console.log(`template written: ${target} (${html.length} chars, ${tokens.size} id groups)`);
